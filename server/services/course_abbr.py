# 规则压缩时优先丢弃的泛词（按长度从长到短处理）
NOISE = [
    "与", "及", "和", "的", "理论", "基础", "原理", "概论", "导论", "教程",
    "大学", "技术", "方法", "实践", "应用", "研究", "学", "论",
]

# 常见后缀：(上)/(下)/A/B/Ⅰ/1 等
_SUFFIX = re.compile(r"[\s]*[（(【\[](?:上|下|一|二|三|I{1,3}|A|B|C|\d+)[)）】\]]\s*$")
_YEAR_PREFIX = re.compile(r"^\s*(?:\d{4}\s*[-—]\s*\d{4}\s*[-—]\s*\d?\s*[-—]?|\d{4}\s*[-—]\s*\d?\s*[-—]?)")
_TRAILING_TEACHER = re.compile(r"[-—]\s*[\u4e00-\u9fa5]{2,4}\s*$")


def _clean(name: str) -> str:
    s = (name or "").strip()

    # 「学年-学期-《课程》-教师」形式：优先取书名号内容
    m = re.search(r"《\s*(.+?)\s*》", s)
    if m:
        s = m.group(1)
    else:
        s = _YEAR_PREFIX.sub("", s)
        s = _TRAILING_TEACHER.sub("", s)

    s = s.replace("（", "(").replace("）", ")")
    s = re.sub(r"\s+", "", s)
    s = _SUFFIX.sub("", s)
    return s.strip(" -—·、")


def _compress(s: str) -> str:
    """规则压缩：逐步去掉泛词，保留前 4 字。"""
    out = s
    for w in NOISE:
        if len(out) <= 4:
            break
        out = out.replace(w, "")
    if not out:
        out = s
    return out[:4]


# 编程语言：面向对象/程序设计类课程优先显示语言，而不是笼统的 OOP
# 注意顺序：javascript / typescript 必须排在 java 前面，否则 "JavaScript" 会被 java 抢先命中
LANG_TOKENS: list[tuple[str, str]] = [
    ("c++", "C++"),
    ("c#", "C#"),
    ("javascript", "JS"),
    ("typescript", "TS"),
    ("java", "Java"),
    ("python", "Python"),
    ("golang", "Go"),
    ("rust", "Rust"),
    ("php", "PHP"),
    ("kotlin", "Kotlin"),
    ("swift", "Swift"),
]

# 触发「显示语言名」的课程类型
LANG_COURSE_HINTS = ("面向对象", "程序设计", "编程", "开发")


def _lang_of(s: str) -> str:
    low = s.lower()
    for token, label in LANG_TOKENS:
        if token in low:
            return label
    return ""


def abbr_of(course_name: str | None) -> str:
    """课程全名 → 简称（2–4 字）。空名返回空串。"""
    s = _clean(course_name or "")
    if not s:
        return ""

    if s in ABBR:
        return ABBR[s]

    # 「Java 面向对象程序设计」这类：直接显示语言名
    lang = _lang_of(s)
    if lang and any(h in s for h in LANG_COURSE_HINTS):
        return lang

    # 包含匹配：命中词条最长者优先，避免「高等数学」被「数学」抢走
    best_key = ""
    best_val = ""
    for k, v in ABBR.items():
        if len(k) >= 2 and k in s and len(k) > len(best_key):
            best_key, best_val = k, v
    if best_key:
        return best_val

    return _compress(s)
